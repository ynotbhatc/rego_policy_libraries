#!/usr/bin/env python3
"""Rego → Kubewarden policies (packaging: OPA wasm with a Kubewarden entrypoint).

Kubewarden runs plain OPA policies compiled to wasm with `opa build -t wasm -e policy/main`,
where `data.policy.main` returns an AdmissionReview response. For each
admission-shaped policy set this writes an adapter package that maps the
AdmissionReview to the policy's input, builds the wasm, and writes the
`metadata.yml` kwctl needs (rules, executionMode: opa). No settings are
read, so the PSS policy is built once per profile.

Output: out/<policy>/{policy.wasm, metadata.yml, adapter.rego}. Annotate and
push with `kwctl annotate` / `kwctl push`.
"""
from __future__ import annotations
import pathlib, subprocess, sys, textwrap

ROOT = pathlib.Path(__file__).resolve().parents[3]
OUT = pathlib.Path(__file__).resolve().parent / "out"

ADAPTER = '''package policy

import rego.v1

# Kubewarden hands the policy an AdmissionReview; `main` answers with one.
_pod := input.request.object if input.request.object.kind == "Pod"

_pod := {"kind": "Pod", "metadata": input.request.object.metadata, "spec": input.request.object.spec.template.spec} if {
\tinput.request.object.kind in {"Deployment", "StatefulSet", "DaemonSet", "ReplicaSet", "Job"}
}

_pod := {"kind": "Pod", "metadata": input.request.object.metadata, "spec": input.request.object.spec.jobTemplate.spec.template.spec} if {
\tinput.request.object.kind == "CronJob"
}

violations := v if {
	v := %(violations)s
}

main := {
\t"apiVersion": "admission.k8s.io/v1",
\t"kind": "AdmissionReview",
\t"response": {
\t\t"uid": object.get(input, ["request", "uid"], ""),
\t\t"allowed": count(violations) == 0,
\t\t"status": {"message": concat("; ", sort(violations))},
\t},
}
'''

POLICIES = [
    {"name": "k8s-pss-baseline", "dir": "benchmarks/pss/kubernetes", "files": None, "entry": "policy/main",
     "violations": 'data.k8s_pss.main.effective_violations with input as {"pod": _pod, "pss_profile": "baseline"}',
     "rules": [{"apiGroups": [""], "apiVersions": ["v1"], "resources": ["pods"], "operations": ["CREATE", "UPDATE"]},
               {"apiGroups": ["apps"], "apiVersions": ["v1"], "resources": ["deployments", "statefulsets", "daemonsets", "replicasets"], "operations": ["CREATE", "UPDATE"]},
               {"apiGroups": ["batch"], "apiVersions": ["v1"], "resources": ["jobs", "cronjobs"], "operations": ["CREATE", "UPDATE"]}]},
    {"name": "k8s-pss-restricted", "dir": "benchmarks/pss/kubernetes", "files": None, "entry": "policy/main",
     "violations": 'data.k8s_pss.main.effective_violations with input as {"pod": _pod, "pss_profile": "restricted"}',
     "rules": None},
    {"name": "k8s-aac-admission", "dir": "enforcement/kubernetes", "files": ["kubernetes_admission.rego"], "entry": "policy/main",
     "violations": 'data.kubernetes.admission.violations',
     "rules": [{"apiGroups": ["", "apps", "batch"], "apiVersions": ["v1"], "resources": ["pods", "deployments", "statefulsets", "daemonsets", "jobs", "cronjobs", "services", "namespaces"], "operations": ["CREATE", "UPDATE"]}]},
]
POLICIES[1]["rules"] = POLICIES[0]["rules"]


def build(p):
    out = OUT / p["name"]; out.mkdir(parents=True, exist_ok=True)
    adapter = ADAPTER % {"violations": p["violations"]}
    (out / "adapter.rego").write_text(adapter)
    srcs = [ROOT / p["dir"] / f for f in p["files"]] if p["files"] else [f for f in sorted((ROOT / p["dir"]).glob("*.rego")) if not f.name.startswith("test_") and not f.name.endswith("_test.rego")]
    bundle = out / "policy.tar.gz"
    subprocess.run(["opa", "build", "-t", "wasm", "-e", p["entry"], "-o", str(bundle), str(out / "adapter.rego")] + [str(s) for s in srcs], check=True, cwd=ROOT)
    subprocess.run(["tar", "-xzf", str(bundle), "-C", str(out), "/policy.wasm"], check=True, capture_output=True)
    bundle.unlink()  # keep only policy.wasm; a tarball in the dir would be loaded by `opa eval -d`
    rules = "\n".join("  - apiGroups: [" + ", ".join(f'"{g}"' for g in r["apiGroups"]) + "]\n    apiVersions: [" + ", ".join(f'"{v}"' for v in r["apiVersions"]) + "]\n    resources: [" + ", ".join(f'"{x}"' for x in r["resources"]) + "]\n    operations: [" + ", ".join(r["operations"]) + "]" for r in p["rules"])
    (out / "metadata.yml").write_text(f"""rules:
{rules}
mutating: false
contextAware: false
executionMode: opa
annotations:
  io.kubewarden.policy.title: {p['name']}
  io.kubewarden.policy.description: "AAC Rego Policy Libraries — generated by converters/packaging/kubewarden/build.py from {p['dir']}"
  io.kubewarden.policy.author: "ynotbhatc/rego_policy_libraries"
  io.kubewarden.policy.url: https://github.com/ynotbhatc/rego_policy_libraries
  io.kubewarden.policy.source: https://github.com/ynotbhatc/rego_policy_libraries
  io.kubewarden.policy.license: Apache-2.0
  io.kubewarden.policy.severity: medium
  io.kubewarden.policy.category: PSP
""")
    for s in srcs:
        (out / s.name).write_text(s.read_text())
    print(f"{p['name']:<20} policy.wasm {((out/'policy.wasm').stat().st_size)/1e3:7.0f} kB  metadata.yml")


def main():
    for p in POLICIES:
        build(p)
    return 0


if __name__ == "__main__":
    sys.exit(main())

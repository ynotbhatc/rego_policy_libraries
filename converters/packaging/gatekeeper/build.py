#!/usr/bin/env python3
"""Rego → Gatekeeper ConstraintTemplates (packaging: the policy source rides inside the template).

Gatekeeper evaluates `violation` in a template whose Rego may use library packages
embedded under `libs:`; those packages must sit under `data.lib`. So for each
admission-shaped policy set this script:

  1. copies the policy source into the template's libs with its package rewritten
     `package X` -> `package lib.X` (and `data.X` references to `data.lib.X`);
  2. adds an adapter rule that maps Gatekeeper's `input.review` to the shape the
     policy expects and surfaces its violations as Gatekeeper `violation` objects;
  3. writes a ConstraintTemplate and an example Constraint to out/.

Only policies that evaluate a Kubernetes object are wrapped: k8s_pss.main (a Pod
or a workload's pod template) and kubernetes.admission (an AdmissionReview). The
CIS/STIG/NSA Kubernetes sets evaluate cluster facts, not admission objects, and
are not Gatekeeper material. Requires Gatekeeper >= 3.17 (Rego v1 via
`source.version: v1`).
"""
from __future__ import annotations
import pathlib, re, subprocess, sys, textwrap

ROOT = pathlib.Path(__file__).resolve().parents[3]
OUT = pathlib.Path(__file__).resolve().parent / "out"

TARGETS = [
    {
        "kind": "K8sPssProfile", "name": "k8spssprofile",
        "src_dir": "benchmarks/pss/kubernetes", "pkg": "k8s_pss.main",
        "params": {"profile": {"type": "string", "enum": ["baseline", "restricted"]}},
        "adapter": '''
_pod := input.review.object if input.review.object.kind == "Pod"

_pod := {"kind": "Pod", "metadata": input.review.object.metadata, "spec": input.review.object.spec.template.spec} if {
\tinput.review.object.kind in {"Deployment", "StatefulSet", "DaemonSet", "ReplicaSet", "Job"}
}

_pod := {"kind": "Pod", "metadata": input.review.object.metadata, "spec": input.review.object.spec.jobTemplate.spec.template.spec} if {
\tinput.review.object.kind == "CronJob"
}

violation contains {"msg": msg} if {
\tsome msg in data.lib.k8s_pss.main.effective_violations with input as {"pod": _pod, "pss_profile": object.get(input.parameters, "profile", "restricted")}
}

# Fail-closed: a matched object with no pod spec this template can evaluate is a violation.
violation contains {"msg": sprintf("object kind %v has no pod spec this constraint can evaluate — refusing", [object.get(input.review.object, "kind", "unknown")])} if {
\tnot _pod
}
''',
        "match_kinds": [{"apiGroups": [""], "kinds": ["Pod"]}, {"apiGroups": ["apps"], "kinds": ["Deployment", "StatefulSet", "DaemonSet", "ReplicaSet"]}, {"apiGroups": ["batch"], "kinds": ["Job", "CronJob"]}],
        "constraint_params": {"profile": "restricted"},
    },
    {
        "kind": "K8sAacAdmission", "name": "k8saacadmission",
        "src_dir": "enforcement/kubernetes", "only_files": ["kubernetes_admission.rego"], "pkg": "kubernetes.admission",
        "params": {},
        "adapter": '''
violation contains {"msg": msg} if {
\tsome msg in data.lib.kubernetes.admission.violations with input as {"request": input.review}
}
''',
        "match_kinds": [{"apiGroups": ["", "apps", "batch"], "kinds": ["Pod", "Deployment", "StatefulSet", "DaemonSet", "Job", "CronJob", "Service", "Namespace"]}],
        "constraint_params": {},
    },
]


def rewrite_to_lib(src: str, pkg: str) -> str:
    top = pkg.split(".")[0]
    src = re.sub(rf"^package {re.escape(pkg)}\s*$", f"package lib.{pkg}", src, flags=re.M)
    src = re.sub(rf"\bdata\.{re.escape(top)}\b", f"data.lib.{top}", src)
    # Gatekeeper rejects annotation metadata blocks in libs; strip the METADATA header lines
    return re.sub(r"^# METADATA\n(#.*\n)+", "", src, flags=re.M)


def yaml_block(text: str, indent: int) -> str:
    pad = " " * indent
    return "\n".join(pad + line if line else "" for line in text.rstrip("\n").split("\n"))


def build(t):
    src_dir = ROOT / t["src_dir"]
    files = [src_dir / f for f in t["only_files"]] if t.get("only_files") else sorted(p for p in src_dir.glob("*.rego") if not p.name.startswith("test_") and not p.name.endswith("_test.rego"))
    libs = [rewrite_to_lib(p.read_text(), t["pkg"]) for p in files]
    adapter = f"package {t['name']}\n\nimport rego.v1\n" + t["adapter"]
    props = "\n".join(f"                {k}:\n                  type: {v['type']}" + ("\n                  enum: [" + ", ".join(v["enum"]) + "]" if "enum" in v else "") for k, v in t["params"].items())
    params_block = f"""          validation:
            openAPIV3Schema:
              type: object
              properties:
{props}
""" if t["params"] else ""
    libs_yaml = "\n".join("            - |\n" + yaml_block(l, 14) for l in libs)
    template = f"""apiVersion: templates.gatekeeper.sh/v1
kind: ConstraintTemplate
metadata:
  name: {t['name']}
  annotations:
    metadata.gatekeeper.sh/title: "AAC Rego Policy Libraries — {t['pkg']}"
    description: "Generated by converters/packaging/gatekeeper/build.py from {t['src_dir']}; do not edit, regenerate."
spec:
  crd:
    spec:
      names:
        kind: {t['kind']}
{params_block}  targets:
    - target: admission.k8s.gatekeeper.sh
      code:
        - engine: Rego
          source:
            version: v1
            rego: |
{yaml_block(adapter, 14)}
            libs:
{libs_yaml}
"""
    cp = "\n".join(f"    {k}: {v}" for k, v in t["constraint_params"].items())
    constraint = f"""apiVersion: constraints.gatekeeper.sh/v1beta1
kind: {t['kind']}
metadata:
  name: {t['name']}-default
spec:
  enforcementAction: deny
  match:
    kinds:
""" + "\n".join("      - apiGroups: [" + ", ".join(f'"{g}"' for g in m["apiGroups"]) + "]\n        kinds: [" + ", ".join(f'"{k}"' for k in m["kinds"]) + "]" for m in t["match_kinds"]) + ("\n  parameters:\n" + cp if cp else "") + "\n"
    (OUT / "templates").mkdir(parents=True, exist_ok=True); (OUT / "constraints").mkdir(parents=True, exist_ok=True)
    (OUT / "templates" / f"{t['name']}-template.yaml").write_text(template)
    (OUT / "constraints" / f"{t['name']}-constraint.yaml").write_text(constraint)
    # also drop the raw adapter + libs for the round-trip test (plain OPA, no cluster)
    rt = OUT / "roundtrip" / t["name"]; rt.mkdir(parents=True, exist_ok=True)
    (rt / "adapter.rego").write_text(adapter)
    for i, l in enumerate(libs):
        (rt / f"lib{i}.rego").write_text(l)
    # committed, Artifact Hub-indexable copy
    dist = pathlib.Path(__file__).resolve().parent / "dist" / t["name"]; (dist / "samples").mkdir(parents=True, exist_ok=True)
    (dist / "template.yaml").write_text(template)
    (dist / "samples" / "constraint.yaml").write_text(constraint)
    # version from CHANGELOG (deterministic in a shallow CI checkout, unlike git describe)
    m = re.search(r"^## \[(\d+\.\d+\.\d+)\]", (ROOT / "CHANGELOG.md").read_text(), re.M)
    version = m.group(1) if m else "0.0.0"
    (dist / "artifacthub-pkg.yml").write_text(f"""version: {version}
name: {t['name']}
displayName: AAC {t['kind']}
createdAt: "2026-10-12T00:00:00Z"
description: "{t['pkg']} from the Rego Policy Libraries as a Gatekeeper ConstraintTemplate — generated, do not edit"
license: Apache-2.0
homeURL: https://github.com/ynotbhatc/rego_policy_libraries
keywords: [opa, gatekeeper, compliance, policy-as-code, kubernetes, pod-security-standards]
links:
  - name: source
    url: https://github.com/ynotbhatc/rego_policy_libraries/tree/main/{t['src_dir']}
  - name: comparison
    url: https://github.com/ynotbhatc/rego_policy_libraries/blob/main/docs/COMPARISON.md
provider:
  name: ynotbhatc
""")
    print(f"{t['name']:<18} template + constraint  libs={len(libs)}  dist/{t['name']}/")


def main():
    for t in TARGETS:
        build(t)
    return 0


if __name__ == "__main__":
    sys.exit(main())

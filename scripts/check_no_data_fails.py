#!/usr/bin/env python3
"""No data never passes: every compliance_report entrypoint, evaluated on input that carries no evidence,
must not report compliant.

Inputs tried per entrypoint: {} (no facts at all). A report "passes" if compliant == true, or if it has
zero violations and zero failed_controls. Entrypoints are discovered the same way the wasm build discovers
them (every `<framework>.main` package with a compliance_report rule).

    python3 scripts/check_no_data_fails.py            # report
    python3 scripts/check_no_data_fails.py --check    # exit 1 on a pass not in the allowlist
    python3 scripts/check_no_data_fails.py --write-test   # regenerate tests/no_data/test_no_data_never_passes.rego
    python3 scripts/check_no_data_fails.py --check-test   # exit 1 if that test file is missing an entrypoint

The generated test is what CI enforces: `opa test` runs it, one test per entrypoint.

Allowlist: scripts/no_data_allowlist.txt, one package per line with a reason, for entrypoints where an
empty input is legitimately compliant (e.g. admission policies with nothing to deny).
"""
from __future__ import annotations
import json, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "converters" / "packaging" / "wasm"))
import build as wasm_build  # noqa: E402

ALLOW = ROOT / "scripts" / "no_data_allowlist.txt"
INPUTS = {"empty": {}}


def entrypoints():
    eps = set()
    for c in wasm_build.discover().values():
        eps |= {e for e in c["entrypoints"] if e.endswith("/compliance_report")}
    return sorted(eps)


def evaluate(eps, inp):
    refs = ", ".join(f'"{e}": object.get(data, {json.dumps(e.split("/"))}, null)' for e in eps)
    q = "{" + refs + "}"
    dirs = sorted({p.split("/")[0] for p in ("benchmarks", "frameworks", "governance", "threat_detection", "crosswalk", "enforcement") if (ROOT / p).exists()})
    cmd = ["opa", "eval", "-I", "-f", "json", "--ignore", "tests", "--ignore", "test_*", "--ignore", "*_test.rego", q]
    for d in dirs:
        cmd += ["-d", str(ROOT / d)]
    out = subprocess.run(cmd, input=json.dumps(inp), capture_output=True, text=True, cwd=ROOT)
    if out.returncode:
        sys.exit(out.stderr)
    return json.loads(out.stdout)["result"][0]["expressions"][0]["value"]


def passes(r):
    if not isinstance(r, dict):
        return False
    if r.get("compliant") is True:
        return True
    v = r.get("violations")
    n = len(v) if isinstance(v, (list, dict)) else r.get("violation_count", 1)
    return n == 0 and r.get("failed_controls", 1) in (0, None)


TEST = ROOT / "tests" / "no_data" / "test_no_data_never_passes.rego"


def render_test(eps, allow):
    out = ["# Generated by scripts/check_no_data_fails.py --write-test. Do not edit by hand.",
           "# No data never passes: every compliance_report entrypoint, evaluated on {}, must not be compliant",
           "# and must report at least one violation or failed control.",
           "package no_data_never_passes_test", "", "import rego.v1", "",
           "_fails(r) if r.compliant == false", "",
           "_fails(r) if count(r.violations) > 0", "",
           "_fails(r) if r.failed_controls > 0", ""]
    for e in eps:
        pkg = e.rsplit("/", 1)[0].replace("/", ".")
        if pkg in allow:
            continue
        name = "test_" + pkg.replace(".", "_") + "_fails_on_no_data"
        ref = "data." + e.replace("/", ".")
        out += [f"{name} if {{", f"\tr := {ref} with input as {{}}", "\t_fails(r)", "}", ""]
    return "\n".join(out).rstrip() + "\n"


def main():
    allow = {l.split()[0] for l in ALLOW.read_text().splitlines() if l.strip() and not l.startswith("#")} if ALLOW.exists() else set()
    eps = entrypoints()
    if "--write-test" in sys.argv or "--check-test" in sys.argv:
        want = render_test(eps, allow)
        if "--write-test" in sys.argv:
            TEST.parent.mkdir(parents=True, exist_ok=True)
            TEST.write_text(want)
            print(f"wrote {TEST.relative_to(ROOT)}")
            return 0
        if not TEST.exists() or TEST.read_text() != want:
            print(f"{TEST.relative_to(ROOT)} is stale; run: python3 scripts/check_no_data_fails.py --write-test")
            return 1
        print("no-data test covers every entrypoint")
        return 0
    bad, undefined = [], []
    for name, inp in INPUTS.items():
        res = evaluate(eps, inp)
        for e in eps:
            pkg = e.rsplit("/", 1)[0].replace("/", ".")
            if res.get(e) is None:
                undefined.append(pkg)
            elif passes(res[e]) and pkg not in allow:
                bad.append((name, pkg))
    print(f"{len(eps)} entrypoints; {len(bad)} pass on no data; {len(undefined)} undefined on empty input")
    for n, p in bad:
        print(f"  PASS-ON-NO-DATA ({n}): {p}")
    for p in sorted(set(undefined)):
        print(f"  UNDEFINED: {p}")
    return 1 if "--check" in sys.argv and bad else 0


if __name__ == "__main__":
    sys.exit(main())

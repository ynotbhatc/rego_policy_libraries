#!/usr/bin/env python3
"""Check an input (facts) document against a framework's generated input schema, before evaluation.

    python3 scripts/validate_input.py <framework key> <input.json>
    python3 scripts/validate_input.py stig.rhel_9 facts.json            # key as in data.<key>.main.compliance_report
    python3 scripts/validate_input.py cis_rhel9 facts.json --partial    # a partial document: skip "required" checks
    python3 scripts/validate_input.py cis_rhel9 facts.json --strict     # any key the module does not read is a problem
    python3 scripts/validate_input.py --list                            # keys that have a schema, with derivation

It reports, with exit status 1 when there is a problem:
  MISSING    a path the policy treats as required evidence is absent or null
  TYPE       a value whose JSON type the module does not accept
  MISNAMED   a key the module does not read that is close to one it does read and that is absent from the
             document (`sshd.permit_root_login` for `ssh_config.PermitRootLogin`): the silent "evidence
             missing" case
Keys the module does not read and that resemble nothing it reads are listed as notes (callers send shared fact
documents), unless --strict.

This is a checker of documents a caller already has. It collects nothing and evaluates no policy. The schemas
are generated by scripts/gen_input_schemas.py (schemas/input/<key>/schema.json); how far to trust one is in
its `x-derivation` (docs/INPUT_SCHEMAS.md). Python standard library only: it implements the JSON Schema
keywords the generator emits (type, properties, required, items, additionalProperties) and nothing else.
"""
from __future__ import annotations
import argparse, difflib, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "schemas" / "input"
IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def schema_path(key, base=SCHEMA_DIR):
    return pathlib.Path(base) / key.replace("/", ".") / "schema.json"


def fmt(path):
    out = ""
    for k in path:
        if k == "[]" or isinstance(k, int):
            out += "[]" if k == "[]" else f"[{k}]"
        elif IDENT.fullmatch(k):
            out += ("." if out else "") + k
        else:
            out += f'["{k}"]'
    return out


def jtype(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "boolean"
    if isinstance(v, (int, float)):
        return "number"
    if isinstance(v, str):
        return "string"
    return "array" if isinstance(v, list) else "object"


def type_ok(v, types):
    types = [types] if isinstance(types, str) else types
    t = jtype(v)
    if t in types:
        return True
    return t == "number" and "integer" in types and float(v).is_integer()


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def close(a, b):
    """a is plausibly a misspelling or a re-casing of b."""
    if a == b:
        return False
    na, nb = norm(a), norm(b)
    if not na or not nb:
        return False
    if na == nb:
        return True
    if min(len(na), len(nb)) < 5:
        return False
    return difflib.SequenceMatcher(None, na, nb).ratio() >= (0.85 if max(len(na), len(nb)) < 20 else 0.93)


def leaf_index(schema):
    """{normalised property name: [(path, is a container), ...]} for every property the schema names, at any depth."""
    idx = {}

    def walk(s, path):
        for k, sub in (s.get("properties") or {}).items():
            idx.setdefault(norm(k), []).append((path + (k,), bool(sub.get("properties") or sub.get("items"))))
            walk(sub, path + (k,))
        if isinstance(s.get("items"), dict):
            walk(s["items"], path + ("[]",))
        if isinstance(s.get("additionalProperties"), dict):
            walk(s["additionalProperties"], path + ("<key>",))
    walk(schema, ())
    return idx


def present(doc, path):
    cur = doc
    for k in path:
        if k in ("[]", "<key>"):
            return True  # a member of a collection: presence of the collection is enough
        if not isinstance(cur, dict) or k not in cur or cur[k] is None:
            return False
        cur = cur[k]
    return True


def validate(schema, doc, partial=False):
    """[{"kind": missing|type|misnamed|unknown, "level": error|note, "path": str, "message": str}]"""
    out, idx = [], leaf_index(schema)

    def add(kind, level, path, msg):
        out.append({"kind": kind, "level": level, "path": fmt(path), "message": msg})

    def elsewhere(k, v, path):
        """A known path, absent from the document, whose last name this unknown key resembles."""
        hits = idx.get(norm(k), [])
        if not 0 < len(hits) <= 2:  # a name used all over (`enabled`, `mode`) identifies nothing
            return None
        for h, container in hits:
            # an unread object is not a misspelt scalar that happens to share its name (`sshd` and `services.sshd`)
            if h != path and container == isinstance(v, (dict, list)) and not present(doc, h):
                return h
        return None

    def unknown_tree(v, path):
        """Under a key the module does not read: only names that match a known, absent path are reported."""
        if isinstance(v, dict):
            for k, sub in v.items():
                h = elsewhere(k, sub, path + (k,))
                if h:
                    add("misnamed", "error", path + (k,), f"not read by this module; did you mean {fmt(h)}?")
                unknown_tree(sub, path + (k,))

    def node(s, v, path, required):
        if v is None:
            types = s.get("type") or []
            if not required and "null" not in ([types] if isinstance(types, str) else types):
                add("type", "note", path, "null (no value supplied)")
            return  # a required null is reported by the parent as missing
        types = s.get("type")
        if types and not type_ok(v, types):
            want = types if isinstance(types, str) else "|".join(types)
            src = " (type seen in the module's passing fixture)" if s.get("x-type-source") == "fixture" else ""
            add("type", "error", path, f"expected {want}, got {jtype(v)}{src}")
            return
        if isinstance(v, dict):
            props = s.get("properties") or {}
            extra = s.get("additionalProperties")
            if not partial:
                for r in s.get("required", []):
                    if v.get(r) is None:
                        why = (props.get(r) or {}).get("x-required-by")
                        add("missing", "error", path + (r,), ("required evidence is null" if r in v else
                            "required evidence not supplied") + (f" ({', '.join(why[:4])}{' …' if len(why) > 4 else ''})" if why else ""))
            for k, sub in v.items():
                if k in props:
                    node(props[k], sub, path + (k,), k in s.get("required", []))
                    continue
                sib = sorted(c for c in props if close(k, c) and v.get(c) is None)
                if sib:
                    add("misnamed", "error", path + (k,), f"not read by this module; did you mean {fmt(path + (sib[0],))}?")
                elif isinstance(extra, dict):
                    node(extra, sub, path + (k,), False)
                    continue
                elif props or not path:
                    h = elsewhere(k, sub, path + (k,))
                    if h:
                        add("misnamed", "error", path + (k,), f"not read by this module; did you mean {fmt(h)}?")
                    else:
                        add("unknown", "note", path + (k,), "not read by this module")
                unknown_tree(sub, path + (k,))
        elif isinstance(v, list) and isinstance(s.get("items"), dict):
            for i, x in enumerate(v):
                node(s["items"], x, path + (i,), False)

    if not isinstance(doc, dict):
        add("type", "error", (), f"the input document must be an object, got {jtype(doc)}")
        return out
    node(schema, doc, (), True)
    return out


def load_schema(key, base=SCHEMA_DIR):
    f = schema_path(key, base)
    if not f.exists():
        return None
    return json.loads(f.read_text())


def main(argv=None):
    ap = argparse.ArgumentParser(description="Check an input document against a framework's generated input schema.")
    ap.add_argument("key", nargs="?", help="framework key, as in data.<key>.main.compliance_report (stig.rhel_9, cis_rhel9)")
    ap.add_argument("input", nargs="?", help="input JSON file ('-' for stdin)")
    ap.add_argument("--partial", action="store_true", help="the document is partial: do not report missing required paths")
    ap.add_argument("--strict", action="store_true", help="any key the module does not read is a problem")
    ap.add_argument("--json", action="store_true", help="print the findings as JSON")
    ap.add_argument("--all", action="store_true", help="list every missing required path (15 by default)")
    ap.add_argument("--list", action="store_true", help="list the keys that have a schema")
    ap.add_argument("--schema-dir", default=str(SCHEMA_DIR))
    a = ap.parse_args(argv)
    base = pathlib.Path(a.schema_dir)
    if a.list:
        for f in sorted(base.glob("*/schema.json")):
            print(f"{f.parent.name}\t{json.loads(f.read_text()).get('x-derivation')}")
        return 0
    if not a.key or not a.input:
        ap.print_usage(sys.stderr)
        return 2
    schema = load_schema(a.key, base)
    if schema is None:
        print(f"no input schema for {a.key!r} ({schema_path(a.key, base)}); --list shows the keys that have one", file=sys.stderr)
        return 2
    try:
        doc = json.load(sys.stdin if a.input == "-" else open(a.input))
    except (OSError, ValueError) as e:
        print(f"cannot read {a.input}: {e}", file=sys.stderr)
        return 2
    notes = []
    if isinstance(doc, dict) and set(doc) == {"input"} and isinstance(doc["input"], dict) and "input" not in schema.get("properties", {}):
        doc = doc["input"]
        notes.append('the document is wrapped as {"input": ...} (the OPA data API form); its content was checked')
    found = validate(schema, doc, partial=a.partial)
    errors = [f for f in found if f["level"] == "error" or (a.strict and f["kind"] == "unknown")]
    rest = [f for f in found if f not in errors]
    if a.json:
        print(json.dumps({"framework_key": schema.get("x-framework-key"), "derivation": schema.get("x-derivation"),
                          "problems": errors, "notes": rest}, indent=2))
        return 1 if errors else 0
    head = f"{schema.get('x-framework-key')} (schema derivation: {schema.get('x-derivation')})"
    print(f"{head}: {len(errors)} problem{'s' if len(errors) != 1 else ''} in {a.input}")
    shown = errors if a.all else [f for f in errors if f["kind"] != "missing"] + [f for f in errors if f["kind"] == "missing"][:15]
    for f in shown:
        print(f"  {f['kind'].upper():10}{f['path']}: {f['message']}")
    if len(shown) < len(errors):
        print(f"  ... and {len(errors) - len(shown)} more MISSING paths (--all lists them; --partial skips the check)")
    for n in notes:
        print(f"  note: {n}")
    unk = [f["path"] for f in rest if f["kind"] == "unknown"]
    if unk:
        print(f"  note: {len(unk)} key(s) this module does not read: {', '.join(unk[:12])}{' …' if len(unk) > 12 else ''}")
    for f in rest:
        if f["kind"] != "unknown":
            print(f"  note: {f['path']}: {f['message']}")
    if not schema.get("required") and not a.partial:
        print("  note: this schema lists no required paths (its derivation cannot tell required evidence from "
              "optional); a document can pass here and still be missing evidence")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())

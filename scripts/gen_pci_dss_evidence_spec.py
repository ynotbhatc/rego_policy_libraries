#!/usr/bin/env python3
"""Generate the `evidence_spec` block of each PCI DSS v4.0.1 requirement module (frameworks/financial/pci_dss).

pci_dss.main reads every module's evidence_spec to tell a requirement that fails on evidence (a fact present and
non-compliant) from one that fails because the facts were never collected ("evidence missing"). The spec is
derived from the rule bodies, so it cannot drift from them by hand:

  gating checks   the rules named by pci_requirement_<n>_compliant, with pure roll-up rules (a single body of
                  bare rule names) expanded to their leaves
  alternatives    every body of a check, helper rules expanded and combined (an else chain is an OR); the
                  check passes when every term of one alternative holds
  terms           [path, test] or [path, test, argument], path relative to input:
                    "true" / "false"  the boolean the rule compares with (== true / == false); a "false" term is
                                      always an applicability gate here (in_scope, service_provider, in_use ...)
                    "ge" / "le"       the number bound of _num_ge / _num_le
                    "within"          _within_defined: a number not above the number at the argument path
                    "str_ge"          a string compared with >= (TLS versions)

A rule body line the generator does not recognise stops it with an error: extend `term()` rather than edit the
block by hand. Re-run after changing a requirement module:
    python3 scripts/gen_pci_dss_evidence_spec.py            # rewrite the blocks
    python3 scripts/gen_pci_dss_evidence_spec.py --check    # exit 1 if a committed block is stale
"""
import itertools, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MOD = ROOT / "frameworks/financial/pci_dss"
BEGIN = "# BEGIN evidence_spec (generated by scripts/gen_pci_dss_evidence_spec.py; do not edit by hand)"
END = "# END evidence_spec"
PATH = r"input\.([a-z0-9_.]+)"


def modules():
    return sorted(MOD.glob("*/requirement_*.rego"), key=lambda p: int(re.search(r"_(\d+)\.rego$", p.name)[1]))


def strip_comment(line):
    out, quoted = [], False
    for ch in line:
        if ch == '"':
            quoted = not quoted
        if ch == "#" and not quoted:
            break
        out.append(ch)
    return "".join(out).rstrip()


def parse_rules(text):
    """{rule name (with its argument list, if any): [body, ...]}, each body a list of expression strings."""
    text = text.split(BEGIN)[0]
    lines = [strip_comment(l) for l in text.splitlines()]
    rules, cur, i = {}, None, 0
    while i < len(lines):
        line = lines[i]
        head = re.match(r"^([a-z_][a-z0-9_]*(?:\([^)]*\))?) if \{$", line)
        if head or line == "} else if {":
            cur = head[1] if head else cur
            body, i = [], i + 1
            while not lines[i].startswith("}"):
                if lines[i].strip():
                    body.append(lines[i].strip())
                i += 1
            rules.setdefault(cur, []).append(body)
            if lines[i] != "} else if {":
                i += 1
            continue
        one = re.match(r"^([a-z_][a-z0-9_]*(?:\([^)]*\))?) if (.+)$", line)
        if one:
            cur = one[1]
            rules.setdefault(cur, []).append([one[2].strip()])
        i += 1
    return rules


def term(expr, rules, where):
    """Alternatives (lists of terms) for one body expression."""
    expr = re.sub(r'\["([a-z0-9_]+)"\]', r".\1", expr).replace("_cust.", "input.pci.passwords.customer_accounts.")
    if expr.startswith("not is_boolean(object.get("):
        return [[]]  # "flag absent" branch of req 8: its other terms carry the evidence
    if m := re.fullmatch(r'_resolved\("([a-z]+)"\)', expr):
        sev = m[1]
        return [[[f"pci.vuln_remediation.{sev}.resolved", "true"]], [[f"pci.vuln_remediation.{sev}.within_30_days", "true"]]]
    if m := re.fullmatch(r'_remote_path_ok\(object\.get\(input, \["pci", "mfa", "([a-z_]+)"\], \{\}\)\)', expr):
        return [[[f"pci.mfa.{m[1]}.mfa_enforced", "true"]], [[f"pci.mfa.{m[1]}.in_use", "false"]]]
    if m := re.fullmatch(PATH + r" == (true|false)", expr):
        return [[[m[1], m[2]]]]
    if m := re.fullmatch(r"_num_(ge|le)\(" + PATH + r", (\d+)\)", expr):
        return [[[m[2], m[1], int(m[3])]]]
    if m := re.fullmatch(r"_within_defined\(" + PATH + ", " + PATH + r"\)", expr):
        return [[[m[1], "within", m[2]]]]
    if m := re.fullmatch(PATH + r' >= "([0-9.]+)"', expr):
        return [[[m[1], "str_ge", m[2]]]]
    if re.fullmatch(r"[a-z_][a-z0-9_]*", expr) and expr in rules:
        return alternatives(expr, rules, where)
    sys.exit(f"gen_pci_dss_evidence_spec: {where}: unrecognised rule body line: {expr}")


def alternatives(name, rules, where):
    out = []
    for body in rules[name]:
        for combo in itertools.product(*[term(e, rules, where) for e in body]):
            alt = []
            for part in combo:
                alt += [t for t in part if t not in alt]
            if alt not in out:
                out.append(alt)
    return out


def block(path):
    n = re.search(r"_(\d+)\.rego$", path.name)[1]
    text = path.read_text()
    rules = parse_rules(text)
    defaults = set(re.findall(r"^default ([a-z_][a-z0-9_]*) := false$", text, re.M))

    # a roll-up is expanded only into checks that default to false, so "passed" is never undefined
    def leaves(names):
        out = []
        for g in names:
            b = rules.get(g)
            if b and len(b) == 1 and all(e in rules and e in defaults for e in b[0]):
                out += leaves(b[0])
            else:
                out.append(g)
        return out

    lines = [
        BEGIN,
        f"# The facts each check that gates pci_requirement_{n}_compliant reads, for pci_dss.main: a failing check is",
        "# \"evidence missing\" when no alternative holds a present, non-compliant fact and some fact is absent or of",
        "# the wrong type. Term tests are described in the generator's docstring.",
        "evidence_spec := {",
    ]
    for check in leaves(rules[f"pci_requirement_{n}_compliant"][0]):
        if check not in defaults:
            sys.exit(f"gen_pci_dss_evidence_spec: {path.name}: gating check {check} has no `default {check} := false`")
        lines.append(f'\t"{check}": {{')
        lines.append(f'\t\t"passed": {check},')
        lines.append('\t\t"alternatives": [')
        for alt in alternatives(check, rules, f"{path.name} {check}"):
            lines.append("\t\t\t[" + ", ".join(json.dumps(t, separators=(", ", ": ")) for t in alt) + "],")
        lines.append("\t\t],")
        lines.append("\t},")
    lines += ["}", "", END]
    return "\n".join(lines)


def render(path):
    text = path.read_text()
    new = block(path)
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        return head + new + tail
    return text.rstrip("\n") + "\n\n" + new + "\n"


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path in modules():
        want = render(path)
        if want != path.read_text():
            stale.append(path)
            if not check:
                path.write_text(want)
    if check and stale:
        for p in stale:
            print(f"stale evidence_spec: {p.relative_to(ROOT)} (run python3 scripts/gen_pci_dss_evidence_spec.py)")
        sys.exit(1)
    if not check:
        print(f"evidence_spec written for {len(modules())} modules ({len(stale)} changed)")


if __name__ == "__main__":
    main()

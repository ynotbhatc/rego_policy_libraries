#!/usr/bin/env python3
"""Generate frameworks/federal/nist/sp_800_53/nist_800_53_index.rego: the static half of the 800-53 per-control results.

  basis      per evaluated id: "attestation" when the control is met by a signed attestation (its finding on empty
             input says "not attested"), otherwise "evidence". Read by evaluating the module on {} with opa.
  baselines  the control ids each imported baseline selects, from converters/exports/oscal/dist/profiles/<key>.json
             (NIST SP 800-53B Low / Moderate / High / Privacy and FedRAMP Rev 5 Low / Moderate / High), written as
             the module writes ids (ac-2.1 -> AC-2(1)). Withdrawn ids are not in any baseline profile.

Deterministic. Re-run after a family module changes its evaluated ids or after `make oscal` rebuilds the profiles:
    python3 scripts/gen_nist_800_53_index.py            # write
    python3 scripts/gen_nist_800_53_index.py --check    # exit 1 if the committed file is stale
"""
import json, pathlib, re, subprocess, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
MOD = ROOT / "frameworks/federal/nist/sp_800_53"
OUT = MOD / "nist_800_53_index.rego"
PROFILES = ROOT / "converters/exports/oscal/dist/profiles"
BASELINES = [  # report key, profile file
    ("nist_low", "nist_800_53_rev5_low"), ("nist_moderate", "nist_800_53_rev5_moderate"),
    ("nist_high", "nist_800_53_rev5_high"), ("nist_privacy", "nist_800_53_rev5_privacy"),
    ("fedramp_low", "fedramp_rev5_low"), ("fedramp_moderate", "fedramp_rev5_moderate"), ("fedramp_high", "fedramp_rev5_high"),
]
ID = re.compile(r"^([a-z]{2})-(\d+)(?:\.(\d+))?$")


def to_id(oscal):
    m = ID.match(oscal)
    assert m, oscal
    return f"{m[1].upper()}-{m[2]}" + (f"({m[3]})" if m[3] else "")


def sort_key(i):
    m = re.match(r"^([A-Z]{2})-(\d+)(?:\((\d+)\))?$", i)
    return (m[1], int(m[2]), int(m[3] or 0))


def empty_input_run():
    q = 'x := {"e": data.nist.sp800_53.main.evaluated_controls, "v": data.nist.sp800_53.main.violations}'
    r = subprocess.run(["opa", "eval", "-f", "json", "-d", str(MOD), "--ignore", "tests", "--ignore", OUT.name, "-i", "/dev/stdin", q],
                       input="{}", capture_output=True, text=True, check=True)
    x = json.loads(r.stdout)["result"][0]["bindings"]["x"]
    return set(x["e"]), x["v"]


def rego_set(ids, indent="\t\t", brackets="{}"):
    ids = sorted(ids, key=sort_key)
    lines, cur = [], ""
    for i in ids:
        tok = json.dumps(i) + ", "
        if len(cur) + len(tok) > 110:
            lines.append(cur.rstrip()); cur = ""
        cur += tok
    if cur: lines.append(cur.rstrip())
    return brackets[0] + "\n" + "\n".join(indent + l for l in lines) + "\n" + indent[:-1] + brackets[1]


def build():
    evaluated, violations = empty_input_run()
    attest = set()
    for v in violations:
        m = re.match(r"^NIST ([A-Z]{2})-([0-9/]+)(\([0-9]+\))?: (.*)$", v)
        assert m, v
        if "not attested" in m[4]:
            attest |= {f"{m[1]}-{n}{m[3] or ''}" for n in m[2].split("/")}
    attest &= evaluated
    out = ['# METADATA',
           '# title: "NIST SP 800-53 Rev 5 — static index for per-control results (basis, baseline membership); generated"',
           '# custom:', '#   class: compliance', '#   framework: nist_sp_800_53', '#   source: nist',
           '#   domains: [us-federal, security-controls]',
           'package nist.sp800_53.index', '', 'import rego.v1', '',
           '# GENERATED by scripts/gen_nist_800_53_index.py — do not edit; re-run the script.', '',
           '# Evaluated ids whose requirement is met by a signed attestation ({attested: true, by, date}); every other',
           '# evaluated id is checked against collected evidence.',
           f'attestation_controls := {rego_set(attest, chr(9))}', '',
           '# Every evaluated id in natural order (AC-2 before AC-10, AC-2 before AC-2(1)): the order of control_results.',
           f'order := {rego_set(evaluated, chr(9), "[]")}', '',
           '# Control ids each baseline selects, in natural order (OSCAL profiles in converters/exports/oscal/dist/profiles, catalog 5.2.0).',
           'baselines := {']
    titles = []
    for key, prof in BASELINES:
        p = json.loads((PROFILES / f"{prof}.json").read_text())["profile"]
        ids = {to_id(i) for imp in p["imports"] for inc in imp.get("include-controls", []) for i in inc["with-ids"]}
        title = p["metadata"]["title"].replace("Rego Policy Libraries — ", "").replace(" (imported baseline)", "")
        out.append(f'\t"{key}": {rego_set(ids, chr(9)*2, "[]")},')
        titles.append(f'\t"{key}": {json.dumps(title)},')
    out.append('}')
    # titles apart from the id lists: an object carrying "title" reads as a control to scripts/count_controls.py
    out += ['', 'baseline_titles := {'] + titles + ['}']
    r = subprocess.run(["opa", "fmt"], input="\n".join(out) + "\n", capture_output=True, text=True, check=True)
    return r.stdout


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else f"{OUT.relative_to(ROOT)} is stale: run scripts/gen_nist_800_53_index.py")
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")

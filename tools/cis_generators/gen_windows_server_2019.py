def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    configure()
    recs, section_names = base.load(pathlib.Path(sys.argv[1]))
    base.TOTAL.clear()
    base.TOTAL.update(recs)
    if len(recs) != TOTAL_RECS:
        sys.exit(f"workbook has {len(recs)} recommendations, expected {TOTAL_RECS}")
    for table, label in ((SECEDIT, "SECEDIT"), (MANUAL, "MANUAL"), (REGISTRY_OVERRIDES, "REGISTRY_OVERRIDES")):
        stray = sorted(set(table) - set(recs))
        if stray:
            sys.exit(f"{label} names ids the workbook does not contain: {stray}")
    manual = {rid for rid, r in recs.items() if r["status"] == "Manual"}
    if manual != set(MANUAL):
        sys.exit(f"Manual recommendations changed: workbook {sorted(manual)}, table {sorted(MANUAL)}")
    if set(base.SECTIONS) != {r["section"] for r in recs.values()}:
        sys.exit(f"sections changed: {sorted({r['section'] for r in recs.values()})}")
    # the generic derivation would also accept these ids under a 2022 meaning; confirm the title still matches
    for rid, words in {"1.1.6": "reversible encryption", "18.9.19.5": "background refresh of Group Policy",
                       "19.7.8.5": "Spotlight collection", "18.10.57.3.10.1": "active but idle",
                       "2.3.5.2": "vulnerable Netlogon", "2.3.10.12": "accessed anonymously"}.items():
        if words not in recs[rid]["title"]:
            sys.exit(f"{rid}: title no longer matches the hand-written logic ({recs[rid]['title']!r})")

    checks = {rid: base.derive(rec) for rid, rec in recs.items()}
    for rid, c in checks.items():
        names = ([c["name"]] if "name" in c else []) + [i[1] for i in c.get("items", [])]
        for n in names:
            if n not in recs[rid]["audit"]:
                sys.exit(f"{rid}: checks {n!r}, which its audit procedure does not name")

    files = {}
    for sec in base.SECTIONS:
        in_sec = {rid: r for rid, r in recs.items() if r["section"] == sec}
        files[f"{base.SECTIONS[sec]}_validation.rego"] = section_module(sec, section_names[sec], in_sec, checks)
    files["attestation_validation.rego"] = base.attestation_module(recs)
    files[f"{PKG}_complete.rego"] = complete_module()
    files["cis_windows_2019_main.rego"] = main_module()
    files["lib.rego"] = lib_text()
    tests = generate_tests(recs, checks)

    for name, text in list(files.items()) + list(tests.items()):
        for stale in ("2022", "5.1.0", "408"):
            if stale in text:
                sys.exit(f"{name}: still mentions {stale!r}")

    for old in OUT.glob("*.rego"):
        old.unlink()
    for old in (OUT / "tests").glob("*.rego"):
        if old.name not in KEEP_TESTS:
            old.unlink()
    (OUT / "data").mkdir(parents=True, exist_ok=True)
    (OUT / "tests").mkdir(exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text)
    for name, text in tests.items():
        if name in KEEP_TESTS:
            sys.exit(f"generated test {name} would overwrite a kept one")
        (OUT / "tests" / name).write_text(text)
    (OUT / "data" / INDEX_NAME).write_text(json.dumps(base.index_doc(recs, section_names), indent=2) + "\n")
    (OUT / "data" / "collector_manifest.json").write_text(
        json.dumps({"collector_manifest": base.manifest(checks)}, indent=2) + "\n")

    kinds = {}
    for c in checks.values():
        kinds[c["kind"]] = kinds.get(c["kind"], 0) + 1
    print(f"{BENCHMARK} v{VERSION}: {len(recs)} recommendations -> {kinds}")


if __name__ == "__main__":
    main()

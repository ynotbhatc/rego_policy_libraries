def generate_tests(recs, checks):
    patch_fixture_facts(checks)
    files = basetests.tests(PKG, base.SECTIONS, recs, checks, MANUAL)
    files = {n: c.replace("# Generated by tools/cis_generators/gen_windows_server_2022.py -- do not edit.",
                          f"# Generated by {GENERATOR} -- do not edit.") for n, c in files.items()}
    extra_tests(recs, checks, files)
    # section 17 facts count as collected only when keyed by a subcategory GUID (see LIB_CHANGES)
    files["test_lib.rego"] = _sub(_rename((HERE / "windows_lib_test.rego.tmpl").read_text()),
                                  [('"{g}"', '"{0cce923f-69ae-11d9-bed3-505054503030}"')], "windows_lib_test.rego.tmpl")
    # Generated test packages live beside the module's namespace, not inside it: the pre-rebuild smoke test
    # evaluates the whole data.cis_windows_server_2019 document, which would otherwise include ~1,500 tests.
    moved = {}
    for name, text in files.items():
        text = text.replace(f"package {PKG}.", f"package {PKG}_tests.")
        text = text.replace(f"data.{PKG}.fixtures_test", f"data.{PKG}_tests.fixtures_test")
        moved[name] = text
    # One small package per module inside the namespace, so scripts/coverage_stamp.py (which matches test
    # packages to modules by name) records every module as tested. No `with input`: the pre-rebuild smoke test
    # evaluates this whole namespace, and rules evaluated without `with` share its cache (no input = no facts).
    head = f"# Generated by {GENERATOR} -- do not edit.\n"
    for mod in ("firewall", "admin_templates_computer", "admin_templates_user"):
        moved[f"test_{mod}_smoke.rego"] = head + f"""package {PKG}.{mod}_test

import rego.v1

test_{mod}_fails_closed_without_input if {{
	r := data.{PKG}.{mod}.compliance_report
	count(r.passed) == 0
	count(r.in_scope) > 0
	count(r.violations) == count(r.in_scope)
}}
"""
    moved["test_attestation_smoke.rego"] = head + f"""package {PKG}.attestation_test

import rego.v1

test_attestation_fails_closed_without_input if {{
	r := data.{PKG}.attestation.compliance_report
	r.compliant == false
	count(r.passed_control_ids) == 0
}}
"""
    moved["test_lib_smoke.rego"] = head + f"""package {PKG}.lib_test

import rego.v1

test_lib_rows_are_not_assessed_without_facts if {{
	data.{PKG}.lib.results["1.1.1"] == "not_assessed"
}}
"""
    return moved



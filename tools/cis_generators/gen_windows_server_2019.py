def _only_sets(checks):
    """privilege -> the SIDs every "is set to" row for it allows: the intersection passes all of them."""
    out = {}
    for c in checks.values():
        if c["kind"] == "rights" and c["mode"] == "only":
            s = set(c["sids"])
            out[c["privilege"]] = out[c["privilege"]] & s if c["privilege"] in out else s
    return out


def patch_fixture_facts(checks):
    """2.2.32 and 2.2.33 (and 2.2.31 on a DC) state different 'only' lists for one right; the compliant fixture
    grants the right to the principals every one of them allows, which passes each as written."""
    allowed = _only_sets(checks)
    orig = basetests._facts

    def facts(c, good):
        if good and c["kind"] == "rights" and c["mode"] == "only":
            return {"secedit": {"privilege_rights": {c["privilege"]: sorted(allowed[c["privilege"]],
                                                                            key=c["sids"].index)}}}
        return orig(c, good)
    basetests._facts = facts


INPUT_REMOVE = {
    "reg": "registry", "reg_all": "registry", "reg_absent": "registry", "ureg": "registry_users",
    "secedit": "secedit/system_access", "rights": "secedit/privilege_rights", "auditpol": "audit_policy",
}


def _role_of(profiles):
    return "ms" if basetests._applies(profiles, "MS") else "dc"


def _fact_keys(c):
    """The input leaves a check reads, to find a role-specific row no row of the other role shares."""
    k = c["kind"]
    if k in ("reg", "reg_absent", "ureg"):
        return {(k == "ureg", c["path"].lower(), c["name"].lower())}
    if k == "reg_all":
        return {(False, i[0].lower(), i[1].lower()) for i in c["items"]}
    if k == "secedit":
        return {("secedit", c["key"])}
    if k == "rights":
        return {("rights", c["privilege"])}
    if k == "auditpol":
        return {("audit", c["guid"])}
    return set()



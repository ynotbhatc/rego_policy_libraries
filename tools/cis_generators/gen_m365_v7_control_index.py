#!/usr/bin/env python3
"""Write benchmarks/cis/saas/m365_v7/control_index.rego from the module's own enumeration.

The CIS Microsoft 365 Foundations Benchmark v7.0.0 module is hand-written; its recommendation list is the committed
keyword digest data/cis_m365_v7_index.json (ids, Automated/Manual, E3/E5 level tags, no titles). The per-control
results in cis_m365_v7_complete.rego need that list in natural id order with each recommendation's profile tags,
and must not read the JSON at evaluation time (its data path depends on how the tree is loaded, and the product
uploads policy files only). This script turns the digest into a Rego literal. No benchmark text is written.

Usage: python3 tools/cis_generators/gen_m365_v7_control_index.py      (no arguments; deterministic)
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
MOD = ROOT / "benchmarks" / "cis" / "saas" / "m365_v7"
GEN = "tools/cis_generators/gen_m365_v7_control_index.py"
TAG = re.compile(r"^(E3|E5) Level ([12])$")


def main():
    doc = json.loads((MOD / "data" / "cis_m365_v7_index.json").read_text())
    recs = doc["recommendations"]
    if len(recs) != doc["total_recommendations"] or len(recs) != 160:
        sys.exit(f"index lists {len(recs)} recommendations, declares {doc['total_recommendations']}; expected 160")
    ids = [r["control_id"] for r in recs]
    if len(set(ids)) != len(ids):
        sys.exit("index repeats a control id")
    rows, scope = [], {}
    for r in sorted(recs, key=lambda r: [int(p) for p in r["control_id"].split(".")]):
        tags = sorted(r["levels"])
        lv = {}
        for t in tags:
            m = TAG.match(t)
            if not m:
                sys.exit(f"{r['control_id']}: unknown profile tag {t!r}")
            lv[m.group(1)] = min(lv.get(m.group(1), 9), int(m.group(2)))
        if not lv:
            sys.exit(f"{r['control_id']}: no profile tag")
        rows.append({"id": r["control_id"], "profile": tags})
        scope[r["control_id"]] = lv
    body = ",\n".join("\t" + json.dumps(x, sort_keys=True) for x in rows)
    sc = ",\n".join(f"\t{json.dumps(k)}: {json.dumps(v, sort_keys=True)}" for k, v in scope.items())
    text = f"""# Generated by {GEN} from data/cis_m365_v7_index.json -- do not edit.
# CIS Microsoft 365 Foundations Benchmark v7.0.0: the {len(rows)} recommendations in natural id order, with the
# licence/level tags the benchmark gives each, for the per-control results in cis_m365_v7_complete.rego.

# METADATA
# title: "CIS Microsoft 365 Foundations Benchmark v7.0.0 -- recommendation index for the per-control results"
# custom:
#   class: security
#   framework: cis_saas
#   source: cis
#   domains: [saas, m365]
package cis_m365_v7.control_index

import rego.v1

CONTROL_INDEX := [
{body},
]

# lowest level at which each licence tier includes the recommendation (absent: not in that tier)
CONTROL_SCOPE := {{
{sc},
}}
"""
    (MOD / "control_index.rego").write_text(text)
    print(f"{len(rows)} recommendations -> {MOD / 'control_index.rego'}")


if __name__ == "__main__":
    main()

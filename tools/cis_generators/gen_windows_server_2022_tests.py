"""Tests for the generated CIS Windows Server 2022 module, built from the same check rows (imported by
gen_windows_server_2022.py).

For each server role a compliant fixture is synthesised from the rows: every recommendation in scope must pass on
it, and the report must count exactly the recommendations the workbook puts in that role's profiles. Then, per
recommendation, the fixture is changed in that recommendation's facts alone and the recommendation must fail. A
row whose logic accepted anything would pass the first test and fail the second; a row whose logic rejected
everything would fail the first.
"""
from __future__ import annotations

import json

USER_SID = "S-1-5-21-1004336348-1177238915-682003330-1001"
OUTSIDER = "S-1-1-0"  # Everyone: named by no recommendation


def _good(op, value):
    if op == "in":
        return value[-1]
    if op == "range":
        return value[0]
    if op == "nonempty":
        return "configured"
    if op == "has_all":
        return ", ".join(value)
    if op == "ne":
        return "renamed-" + value.lower()
    return value


def _bad(op, value):
    if op == "in":
        return max(value) + 1
    if op == "eq":
        return value + 1 if isinstance(value, int) else "BROKEN"
    if op in ("ge", "ge_or_forever"):
        return value - 1
    if op == "le":
        return value + 1
    if op == "le_not0":
        return 0
    if op == "range":
        return value[1] + 1
    if op == "nonempty":
        return ""
    if op == "set":
        return ["BROKEN"]
    if op == "has_all":
        return value[0]
    if op == "ne":
        return value
    raise ValueError(op)


def _facts(c, good):
    """The facts one check reads, as a partial input document."""
    k = c["kind"]
    pick = _good if good else _bad
    if k == "reg":
        return {"registry": {c["path"]: {c["name"]: pick(c["op"], c["value"])}}}
    if k == "reg_all":
        out = {}
        for n, (path, name, op, value) in enumerate(c["items"]):
            v = _good(op, value) if (good or n > 0) else _bad(op, value)
            out.setdefault(path, {})[name] = v
        return {"registry": out}
    if k == "reg_absent":
        return {} if good else {"registry": {c["path"]: {c["name"]: 1}}}
    if k == "ureg":
        return {"registry_users": {USER_SID: {c["path"]: {c["name"]: pick(c["op"], c["value"])}}}}
    if k == "secedit":
        return {"secedit": {"system_access": {c["key"]: pick(c["op"], c["value"])}}}
    if k == "rights":
        if good:
            held = list(c["sids"])
        else:
            held = {"none": [OUTSIDER], "only": list(c["sids"]) + [OUTSIDER], "include": []}[c["mode"]]
        return {"secedit": {"privilege_rights": {c["privilege"]: held}}}
    if k == "auditpol":
        return {"audit_policy": {c["guid"]: 3 if good else 0}}
    raise ValueError(k)


def _merge(dst, src, where, owner, owners):
    for key, val in src.items():
        path = where + (key,)
        if isinstance(val, dict) and val:
            node = dst.setdefault(key, {})
            if not isinstance(node, dict):
                raise SystemExit(f"fixture conflict at {path}")
            _merge(node, val, path, owner, owners)
        else:
            if key in dst and dst[key] != val:
                raise SystemExit(f"fixture conflict at {'/'.join(path)}: {owners[path]} and {owner} need different values")
            dst[key] = val
            owners[path] = owner


def _applies(profiles, role):
    return any(p.endswith("_" + role) for p in profiles)


def _fixture(role, checks, recs, manual):
    fx = {"cis_profile": {"role": {"MS": "member_server", "DC": "domain_controller"}[role], "level": 2,
                          "next_generation": True},
          "registry": {}, "registry_users": {USER_SID: {}}, "audit_policy": {},
          "secedit": {"system_access": {}, "privilege_rights": {}}}
    owners = {}
    for rid, c in checks.items():
        if c["kind"] == "manual" or not _applies(recs[rid]["profiles"], role):
            continue
        _merge(fx, _facts(c, True), (), rid, owners)
    fx["attestations"] = [{"control_id": rid, "attested_by": "test", "attested_on": "2026-10-15",
                           "evidence_ref": "test"} for rid in sorted(manual) if _applies(recs[rid]["profiles"], role)]
    return fx


def tests(pkg, sections, recs, checks, manual):
    """{file name: content}: one test package per module, so each module is recorded as tested."""
    order = sorted(recs, key=lambda i: [int(p) for p in i.split(".")])
    fixtures = {role: _fixture(role, checks, recs, manual) for role in ("MS", "DC")}
    expected = {role: sum(1 for rid in recs if _applies(recs[rid]["profiles"], role)) for role in ("MS", "DC")}
    head = "# Generated by tools/cis_generators/gen_windows_server_2022.py -- do not edit.\n"
    fx = f"data.{pkg}.fixtures_test"
    files = {}

    body = [head + f"package {pkg}.fixtures_test\n\nimport rego.v1\n",
            "# A compliant host per role, synthesised from the check rows: every recommendation in scope passes.\n"]
    for role in ("MS", "DC"):
        body.append(f"fixture_{role.lower()} := {json.dumps(fixtures[role], indent=1, sort_keys=True)}\n")
    files["test_fixtures.rego"] = "\n".join(body)

    for sec_no, sec in sections.items():
        body = [head + f"package {pkg}.{sec}_test\n\nimport rego.v1\n"]
        for rid in order:
            c = checks[rid]
            if c["kind"] == "manual" or recs[rid]["section"] != sec_no:
                continue
            role = "MS" if _applies(recs[rid]["profiles"], "MS") else "DC"
            # object.union merges objects recursively and replaces arrays: only this recommendation's facts change.
            # lib.results is looked up by id, so only this row is evaluated.
            body.append(f"""test_{rid.replace(".", "_")}_fails_when_its_facts_do_not_comply if {{
	data.{pkg}.lib.results["{rid}"] == "fail" with input as object.union({fx}.fixture_{role.lower()}, {json.dumps(_facts(c, False))})
}}
""")
        files[f"test_{sec}.rego"] = "\n".join(body)

    ms_only = next(rid for rid in order if checks[rid]["kind"] != "manual" and recs[rid]["profiles"] == ["L1_MS"])
    l2_only = next(rid for rid in order if checks[rid]["kind"] != "manual"
                   and all(p.startswith("L2") for p in recs[rid]["profiles"]))
    ng_only = next(rid for rid in order if all(p.startswith("NG") for p in recs[rid]["profiles"]))
    sec = lambda rid: sections[rid.split(".")[0]]  # noqa: E731
    body = [head + f"package {pkg}.main_test\n\nimport rego.v1\n"]
    for role in ("MS", "DC"):
        body.append(f"""test_{role.lower()}_compliant_fixture_passes_every_recommendation if {{
	r := data.{pkg}.main.compliance_report with input as {fx}.fixture_{role.lower()}
	r.total_controls == {expected[role]}
	r.failed_controls == 0
	r.passed_controls == {expected[role]}
	r.compliant == true
	r.assessment_coverage_percentage == 100
	count(r.violations) == 0
}}
""")
    body.append(f"""test_empty_input_fails_closed if {{
	r := data.{pkg}.main.compliance_report with input as {{}}
	r.compliant == false
	r.passed_controls == 0
	r.failed_controls == r.total_controls
	r.total_controls > 0
	some v in r.violations
	startswith(v, "FAIL-CLOSED")
}}

test_no_input_document_fails_closed if {{
	r := data.{pkg}.main.compliance_report
	r.compliant == false
	r.passed_controls == 0
}}

test_coverage_accounting_partitions_the_benchmark if {{
	r := data.{pkg}.main.compliance_report with input as {{}}
	r.coverage_accounting.balanced == true
	r.coverage_accounting.accounted == {len(recs)}
}}

test_role_not_supplied_leaves_role_specific_recommendations_not_assessed if {{
	fx := json.remove({fx}.fixture_ms, ["cis_profile/role"])
	r := data.{pkg}.{sec(ms_only)}.compliance_report with input as fx
	r.results["{ms_only}"] == "not_assessed"
	m := data.{pkg}.main.compliance_report with input as fx
	m.compliant == false
}}

test_level_1_excludes_level_2_recommendations if {{
	fx := json.patch({fx}.fixture_ms, [{{"op": "replace", "path": "/cis_profile/level", "value": 1}}])
	r := data.{pkg}.{sec(l2_only)}.compliance_report with input as fx
	r.results["{l2_only}"] == "not_applicable"
}}

test_next_generation_is_opt_in if {{
	fx := json.remove({fx}.fixture_ms, ["cis_profile/next_generation"])
	r := data.{pkg}.{sec(ng_only)}.compliance_report with input as fx
	r.results["{ng_only}"] == "not_applicable"
}}

test_missing_audit_policy_is_reported_not_assessed if {{
	fx := json.remove({fx}.fixture_ms, ["audit_policy"])
	r := data.{pkg}.main.compliance_report with input as fx
	"Advanced Audit Policy Configuration" in r.sections_not_assessed
	r.missing_inputs["Advanced Audit Policy Configuration"] == ["audit_policy"]
	r.compliant == false
}}
""")
    files["test_main.rego"] = "\n".join(body)

    automated = sum(1 for c in checks.values() if c["kind"] != "manual")
    files["test_complete.rego"] = head + f"""package {pkg}_test

import rego.v1

test_every_automated_recommendation_has_a_row if {{
	count(data.{pkg}.evaluated_control_ids) == {automated}
}}

test_member_server_scope_matches_the_workbook if {{
	count(data.{pkg}.applicable_ids) == {expected["MS"]} with input as {fx}.fixture_ms
}}

test_domain_controller_scope_matches_the_workbook if {{
	count(data.{pkg}.applicable_ids) == {expected["DC"]} with input as {fx}.fixture_dc
}}
"""

    files["test_attestation.rego"] = head + f"""package {pkg}.attestation_test

import rego.v1

test_unattested_manual_recommendation_is_a_violation if {{
	fx := json.remove({fx}.fixture_ms, ["attestations"])
	r := data.{pkg}.main.compliance_report with input as fx
	r.compliant == false
	r.unattested_controls == {sum(1 for rid in manual if _applies(recs[rid]["profiles"], "MS"))}
}}

test_incomplete_attestation_is_not_evidence if {{
	fx := json.patch({fx}.fixture_ms, [{{"op": "replace", "path": "/attestations/0/evidence_ref", "value": null}}])
	r := data.{pkg}.attestation.compliance_report with input as fx
	some v in r.violations
	contains(v, "not admissible evidence")
}}

test_complete_attestation_passes if {{
	r := data.{pkg}.attestation.compliance_report with input as {fx}.fixture_ms
	r.compliant == true
}}
"""
    return files

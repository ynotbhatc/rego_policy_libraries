def load(path):
    rows = base.read_sheet(path, "Combined Profiles")
    ix = {h: i for i, h in enumerate(rows[0])}
    recs, section_names = {}, {}
    for r in rows[1:]:
        cell = lambda name: (r[ix[name]] if ix[name] < len(r) else None) or ""  # noqa: E731
        sec, rid = cell("Section #"), cell("Recommendation #")
        if sec and not rid and "." not in sec:
            section_names[sec] = cell("Title")
        if not rid:
            continue
        profile = cell("Profile").strip()
        if profile not in base.PROFILE_CODES:
            sys.exit(f"{rid}: unrecognised profile {profile!r}")
        code = base.PROFILE_CODES[profile]
        title = " ".join(cell("Title").split())
        if TIER.match(title):
            sys.exit(f"{rid}: the title carries a tier prefix this reader does not expect")
        rec = {"id": rid, "title": title, "status": cell("Assessment Status"),
               "audit": cell("Audit Procedure"), "section": rid.split(".")[0]}
        if rid not in recs:
            recs[rid] = dict(rec, profiles=[code])
            continue
        seen = recs[rid]
        if {k: v for k, v in seen.items() if k != "profiles"} != rec:
            sys.exit(f"{rid}: listed twice with different content")
        if code in seen["profiles"]:
            sys.exit(f"{rid}: listed twice in {profile!r}")
        seen["profiles"] = sorted(seen["profiles"] + [code])
    for rid, rec in recs.items():
        if len({p.split("_")[0] for p in rec["profiles"]}) != 1:
            sys.exit(f"{rid}: listed in more than one tier {rec['profiles']}")
        m = ROLE_SUFFIX.search(rec["title"])
        if m and {p.split("_")[1] for p in rec["profiles"]} != {m.group(1)}:
            sys.exit(f"{rid}: the title says {m.group(1)} only, the profiles are {rec['profiles']}")
    return recs, section_names


def derive(rec):
    check = base.derive(rec)
    # derive_rights reads the first quoted principal list only: nothing but a role suffix may follow it
    if check["kind"] == "rights":
        m = re.match(r"Ensure '[^']+'\s+(?:is set to|to include) '[^']+'(.*)$", rec["title"])
        rest = ROLE_SUFFIX.sub("", m.group(1)).strip() if m else None
        if rest:
            sys.exit(f"{rec['id']}: the user-rights title continues past its principal list")
        # A deny right "is set to" a list: denying fewer principals is the weaker state, so every named principal
        # must be denied and denying more is allowed ("only" would pass a host that denies no one).
        if check["privilege"].startswith("SeDeny") and check["mode"] == "only":
            if rec["id"] not in DENY_IS_SET_TO:
                sys.exit(f"{rec['id']}: a deny right stated with 'is set to' that DENY_IS_SET_TO does not list")
            check["mode"] = "include"
            DENY_SEEN.add(rec["id"])
    return check



def configure():
    """Point the 2019 generator's module-level names at 2016; its functions read them when called."""
    g19.BENCHMARK, g19.SHORT, g19.VERSION, g19.PKG, g19.DIR = BENCHMARK, SHORT, VERSION, PKG, DIR
    g19.TOTAL_RECS, g19.INDEX_NAME, g19.GENERATOR, g19.MAIN_FILE = TOTAL_RECS, INDEX_NAME, GENERATOR, MAIN_FILE
    g19.SECEDIT, g19.MANUAL, g19.REGISTRY_OVERRIDES = SECEDIT, MANUAL, REGISTRY_OVERRIDES
    g19.SIDS = dict(base.SIDS)
    g19.EXTRA_PRIVILEGES, g19.TITLE_WORDS = EXTRA_PRIVILEGES, TITLE_WORDS
    g19.DENY_IS_SET_TO, g19.ZERO_BOUND_IDS = DENY_IS_SET_TO, ZERO_BOUND_IDS
    g19.KEEP_TESTS = set()
    g19.STALE = ("2022", "_2019", "2019_", "2019 Benchmark", "5.1.0", "5.0.0", "408")
    g19.load, g19.derive = load, derive
    g19.section_module_fn = base.section_module  # no pre-rebuild `report` / `violations` section aliases here
    g19.lib_text, g19.main_module, g19.generate_tests = lib_text, main_module, generate_tests
    g19.compliance_assessment = compliance_assessment


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    configure()
    hand = (set(SECEDIT) | set(MANUAL) | set(REGISTRY_OVERRIDES) | set(MULTI_VALUE_OPS) | set(CONDITIONAL_PRINCIPALS))
    if hand - set(TITLE_WORDS):
        sys.exit(f"hand-written entries without a title keyword: {sorted(hand - set(TITLE_WORDS))}")
    recs, section_names, checks = g19.generate(sys.argv[1])
    for rid, rec in recs.items():
        if TIER.search(rec["title"]):
            sys.exit(f"{rid}: a tier prefix survived in the title")
    (base.OUT / "README.md").write_text(readme(recs, section_names, checks))
    # the emitted Rego is not in `opa fmt` layout (three files differ); format it so a second run changes nothing
    if shutil.which("opa"):
        subprocess.run(["opa", "fmt", "-w", str(base.OUT)], check=True)
    else:
        print(f"  opa not found: run `opa fmt -w benchmarks/cis/{DIR}` before committing")
    tiers = {t: sum(1 for r in recs.values() if r["profiles"][0].startswith(t)) for t in ("L1", "L2", "NG")}
    print(f"  {len(recs) - len(MANUAL)} Automated, {len(MANUAL)} Manual; tiers {tiers}")


if __name__ == "__main__":
    main()

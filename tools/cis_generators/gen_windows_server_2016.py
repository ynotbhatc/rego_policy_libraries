def load(path):
    rows = base.read_sheet(path, "Combined Profiles")
    ix = {h: i for i, h in enumerate(rows[0])}
    recs, section_names = {}, {}
    for r in rows[1:]:
        cell = lambda name: (r[ix[name]] if ix[name] < len(r) else None) or ""  # noqa: E731
        sec, rid = cell("Section #"), cell("Recommendation #")
        if sec and not rid and "." not in sec:
            section_names[sec] = cell("Title")
        if not rid:
            continue
        profile = cell("Profile").strip()
        if profile not in base.PROFILE_CODES:
            sys.exit(f"{rid}: unrecognised profile {profile!r}")
        code = base.PROFILE_CODES[profile]
        title = " ".join(cell("Title").split())
        m = TIER.match(title)
        if not m or m.group(1) != code.split("_")[0]:
            sys.exit(f"{rid}: the title's tier does not match its profile {profile!r} ({title[:40]!r})")
        rec = {"id": rid, "title": title[m.end():], "status": cell("Assessment Status"),
               "audit": cell("Audit Procedure"), "section": rid.split(".")[0]}
        if rid not in recs:
            recs[rid] = dict(rec, profiles=[code])
            continue
        seen = recs[rid]
        if {k: v for k, v in seen.items() if k != "profiles"} != rec:
            sys.exit(f"{rid}: listed twice with different content")
        if code in seen["profiles"]:
            sys.exit(f"{rid}: listed twice in {profile!r}")
        seen["profiles"] = sorted(seen["profiles"] + [code])
    for rid, rec in recs.items():
        if len({p.split("_")[0] for p in rec["profiles"]}) != 1:
            sys.exit(f"{rid}: listed in more than one tier {rec['profiles']}")
    return recs, section_names


# ---------------------------------------------------------------------------------------------------------------
# Derivation: the 2022 logic plus a bound inside a several-value row and a conditionally allowed principal
# ---------------------------------------------------------------------------------------------------------------

def derive(rec):
    rid = rec["id"]
    check = base.derive(rec)
    if rid in MULTI_VALUE_OPS:
        wanted = dict(MULTI_VALUE_OPS[rid])
        if check["kind"] != "reg_all":
            sys.exit(f"{rid}: expected a several-value registry row, derived {check['kind']}")
        for item in check["items"]:
            if item[1] in wanted:
                op, value = wanted.pop(item[1])
                if item[2] != "eq" or item[3] != value:
                    sys.exit(f"{rid}: the audit procedure states {item[3]!r} for {item[1]}, the table {value!r}")
                item[2] = op
        if wanted:
            sys.exit(f"{rid}: the audit procedure does not name {sorted(wanted)}")
    if rid in CONDITIONAL_PRINCIPALS:
        name, sid = CONDITIONAL_PRINCIPALS[rid]
        if check["kind"] != "rights" or check["mode"] != "only" or f"'{name}'" not in rec["title"]:
            sys.exit(f"{rid}: expected an 'is set to' user-rights row that names {name}")
        check["sids"] = check["sids"] + [sid]
    return check



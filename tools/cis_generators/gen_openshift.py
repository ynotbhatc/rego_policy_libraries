def wrap(idlist, width=112):
    out, line = [], "#   "
    for i in idlist:
        if len(line) + len(i) + 2 > width:
            out.append(line.rstrip())
            line = "#   "
        line += i + ", "
    out.append(line.rstrip().rstrip(","))
    return "\n".join(out)


